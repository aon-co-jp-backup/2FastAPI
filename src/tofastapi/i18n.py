def text(lang: str, key: str, **kw) -> str:
    """Return the string for `lang`; the default language shows English and Japanese together."""
    if lang == "default":
        a = S["en"][key].format(**kw) if kw else S["en"][key]
        b = S["ja"][key].format(**kw) if kw else S["ja"][key]
        return a if a == b else a + "\n" + b
    s = S.get(lang, S["en"])[key]
    return s.format(**kw) if kw else s


def is_rtl(lang: str) -> bool:
    return any(c == lang and d == "rtl" for c, _, d in LANGS)
